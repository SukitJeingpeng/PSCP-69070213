"""ROAM"""

NUMBER = int(input())

if NUMBER < 0:
    print("Error : Please input positive number")
else:
    if NUMBER == 1:
        print("I")
    elif NUMBER == 2:
        print("II")
    elif NUMBER == 3:
        print("III")
    elif NUMBER == 4:
        print("IV")
    elif NUMBER == 5:
        print("V")
    elif NUMBER == 6:
        print("VI")
    elif NUMBER == 7:
        print("VII")
    elif NUMBER == 8:
        print("IIX")
    elif NUMBER == 9:
        print("IX")
    elif NUMBER == 10:
        print("X")
    else:
        print("Error : Out of range")
