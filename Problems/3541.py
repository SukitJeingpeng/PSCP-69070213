"""COKE"""

PRICE = int(input())
CAPS_NEEDED = int(input())
DISCOUNT_PRICE = int(input())
WANTED_BOTTLES = int(input())

if not CAPS_NEEDED or not WANTED_BOTTLES:
    TOTAL_COST = WANTED_BOTTLES * PRICE
else:
    DISCOUNTED_BOTTLES = (WANTED_BOTTLES - 1) // CAPS_NEEDED
    FULL_PRICE_BOTTLES = WANTED_BOTTLES - DISCOUNTED_BOTTLES
    TOTAL_COST = (FULL_PRICE_BOTTLES * PRICE) + (DISCOUNTED_BOTTLES * DISCOUNT_PRICE)

print(TOTAL_COST)
